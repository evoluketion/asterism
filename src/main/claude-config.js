'use strict';

const fs = require('fs');
const path = require('path');

// Events delivered via Claude Code's native HTTP hooks. SessionStart doesn't support HTTP hooks,
// so it uses the exec form (command + args, no shell) with curl, which ships with Windows 10+.
const HTTP_EVENTS = [
  'UserPromptSubmit', 'PreToolUse', 'PostToolUse', 'PostToolUseFailure', 'PermissionRequest',
  'PermissionDenied', 'Notification', 'Stop', 'StopFailure', 'SessionEnd',
];
const TOOL_EVENTS = new Set(['PreToolUse', 'PostToolUse', 'PostToolUseFailure', 'PermissionRequest', 'PermissionDenied']);

const MCP_NAME = 'asterism';
const MCP_TOOLS = ['list_panes', 'get_pane_transcript', 'read_pane_screen'];

function buildSettings({ port, token, paneId }) {
  const base = `http://127.0.0.1:${port}/hook/${paneId}`;
  const headers = { Authorization: `Bearer ${token}` };
  const hooks = {};
  for (const event of HTTP_EVENTS) {
    const entry = { hooks: [{ type: 'http', url: `${base}/${event}`, headers, timeout: 3 }] };
    if (TOOL_EVENTS.has(event)) entry.matcher = '*';
    hooks[event] = [entry];
  }
  hooks.SessionStart = [{
    hooks: [{
      type: 'command',
      command: process.platform === 'win32' ? 'curl.exe' : 'curl',
      args: ['-s', '-m', '2', '-X', 'POST', '--data-binary', '@-',
        '-H', 'Content-Type: application/json', '-H', `Authorization: Bearer ${token}`,
        `${base}/SessionStart`],
      timeout: 5,
    }],
  }];
  return {
    hooks,
    // The status tools are read-only, so don't make the user approve every call.
    permissions: { allow: MCP_TOOLS.map(t => `mcp__${MCP_NAME}__${t}`) },
  };
}

function buildMcpConfig({ port, token, paneId }) {
  return {
    mcpServers: {
      [MCP_NAME]: {
        type: 'http',
        url: `http://127.0.0.1:${port}/mcp/${paneId}`,
        headers: { Authorization: `Bearer ${token}` },
      },
    },
  };
}

function writePrivate(file, content, mode = 0o600) {
  fs.writeFileSync(file, typeof content === 'string' ? content : JSON.stringify(content, null, 2), { mode });
  try { fs.chmodSync(file, mode); } catch {}
}

const qPosix = s => `'${String(s).replace(/'/g, `'\\''`)}'`;

// The claude command as it should appear in the shim: an absolute path is quoted, anything else
// (e.g. "claude", or "node /path/fake.js") is used verbatim.
function shimCommand(cmd, quote) {
  const c = (cmd || 'claude').trim();
  return path.isAbsolute(c) && fs.existsSync(c) ? quote(c) : c;
}

// Per-pane runtime files: hook settings, MCP config, and a `claude` shim that injects them.
// The shim goes first on the pane's PATH, so any `claude` started in the pane — by Asterism or typed by
// hand after a cd — reports its status. It removes its own folder from PATH before running the
// real claude, so it never calls itself.
function preparePane({ runtimeDir, port, token, paneId, claudeCommand }) {
  const paneDir = path.join(runtimeDir, paneId);
  const binDir = path.join(paneDir, 'bin');
  fs.mkdirSync(binDir, { recursive: true });
  const settingsFile = path.join(paneDir, 'settings.json');
  const mcpFile = path.join(paneDir, 'mcp.json');
  writePrivate(settingsFile, buildSettings({ port, token, paneId }));
  writePrivate(mcpFile, buildMcpConfig({ port, token, paneId }));

  if (process.platform === 'win32') {
    const cmd = shimCommand(claudeCommand, c => `"${c}"`);
    writePrivate(path.join(binDir, 'claude.cmd'), [
      '@echo off',
      'setlocal',
      `set "PATH=%PATH:${binDir};=%"`,
      `${cmd} --settings "${settingsFile}" --mcp-config "${mcpFile}" %*`,
      '',
    ].join('\r\n'), 0o700);
  } else {
    const cmd = shimCommand(claudeCommand, qPosix);
    writePrivate(path.join(binDir, 'claude'), [
      '#!/bin/sh',
      '# Generated by Asterism: runs claude with this pane\'s status hooks.',
      `d=${qPosix(binDir)}`,
      'set -f; new=; IFS=:',
      'for p in $PATH; do [ "$p" = "$d" ] || new="${new:+$new:}$p"; done',
      'unset IFS; set +f; PATH=$new; export PATH',
      `exec ${cmd} --settings ${qPosix(settingsFile)} --mcp-config ${qPosix(mcpFile)} "$@"`,
      '',
    ].join('\n'), 0o700);
  }
  return { paneDir, binDir, initDir: path.join(paneDir, 'init') };
}

function cleanup(runtimeDir, paneId) {
  try { fs.rmSync(path.join(runtimeDir, paneId), { recursive: true, force: true }); } catch {}
}

function cleanupAll(runtimeDir) {
  try { fs.rmSync(runtimeDir, { recursive: true, force: true }); } catch {}
}

module.exports = { buildSettings, buildMcpConfig, preparePane, cleanup, cleanupAll, MCP_TOOLS };
